import 'dart:typed_data';
import 'package:flutter_test/flutter_test.dart';
import 'package:crypto/crypto.dart' as crypto;
import 'package:cbi_app/src/id_reader/data/crypto/pace_crypto.dart';

void main() {
  test('RFC 4493 AES-128 CMAC Test Vectors', () {
    final key = Uint8List.fromList([
      0x2b, 0x7e, 0x15, 0x16, 0x28, 0xae, 0xd2, 0xa6,
      0xab, 0xf7, 0x15, 0x88, 0x09, 0xcf, 0x4f, 0x3c
    ]);

    // Example 1: len = 0
    final mac0 = PaceCrypto.computeAesCmac64(key, Uint8List(0), macBytes: 16);
    expect(
      mac0.map((b) => b.toRadixString(16).padLeft(2, '0')).join().toUpperCase(),
      'BB1D6929E95937287FA37D129B756746',
    );

    // Example 2: len = 16
    final msg16 = Uint8List.fromList([
      0x6b, 0xc1, 0xbe, 0xe2, 0x2e, 0x40, 0x9f, 0x96,
      0xe9, 0x3d, 0x7e, 0x11, 0x73, 0x93, 0x17, 0x2a
    ]);
    final mac16 = PaceCrypto.computeAesCmac64(key, msg16, macBytes: 16);
    expect(
      mac16.map((b) => b.toRadixString(16).padLeft(2, '0')).join().toUpperCase(),
      '070A16B46B4D4144F79BDD9DD04A287C',
    );

    // Example 3: len = 40
    final msg40 = Uint8List.fromList([
      0x6b, 0xc1, 0xbe, 0xe2, 0x2e, 0x40, 0x9f, 0x96,
      0xe9, 0x3d, 0x7e, 0x11, 0x73, 0x93, 0x17, 0x2a,
      0xae, 0x2d, 0x8a, 0x57, 0x1e, 0x03, 0xac, 0x9c,
      0x9e, 0xb7, 0x6f, 0xac, 0x45, 0xaf, 0x8e, 0x51,
      0x30, 0xc8, 0x1c, 0x46, 0xa3, 0x5c, 0xe4, 0x11
    ]);
    final mac40 = PaceCrypto.computeAesCmac64(key, msg40, macBytes: 16);
    expect(
      mac40.map((b) => b.toRadixString(16).padLeft(2, '0')).join().toUpperCase(),
      'DFA66747DE9AE63030CA32611497C827',
    );

    // Example 4: len = 64
    final msg64 = Uint8List.fromList([
      0x6b, 0xc1, 0xbe, 0xe2, 0x2e, 0x40, 0x9f, 0x96,
      0xe9, 0x3d, 0x7e, 0x11, 0x73, 0x93, 0x17, 0x2a,
      0xae, 0x2d, 0x8a, 0x57, 0x1e, 0x03, 0xac, 0x9c,
      0x9e, 0xb7, 0x6f, 0xac, 0x45, 0xaf, 0x8e, 0x51,
      0x30, 0xc8, 0x1c, 0x46, 0xa3, 0x5c, 0xe4, 0x11,
      0xe5, 0xfb, 0xc1, 0x19, 0x1a, 0x0a, 0x52, 0xef,
      0xf6, 0x9f, 0x24, 0x45, 0xdf, 0x4f, 0x9b, 0x17,
      0xad, 0x2b, 0x41, 0x7b, 0xe6, 0x6c, 0x37, 0x10
    ]);
    final mac64 = PaceCrypto.computeAesCmac64(key, msg64, macBytes: 16);
    expect(
      mac64.map((b) => b.toRadixString(16).padLeft(2, '0')).join().toUpperCase(),
      '51F0BEBF7E3B9D92FC49741779363CFE',
    );
  });

  test('SP 800-38B AES-256 CMAC Test Vectors', () {
    final key256 = Uint8List.fromList([
      0x60, 0x3d, 0xeb, 0x10, 0x15, 0xca, 0x71, 0xbe,
      0x2b, 0x73, 0xae, 0xf0, 0x85, 0x7d, 0x77, 0x81,
      0x1f, 0x35, 0x2c, 0x07, 0x3b, 0x61, 0x08, 0xd7,
      0x2d, 0x98, 0x10, 0xa3, 0x09, 0x14, 0xdf, 0xf4
    ]);

    // len = 0
    final mac0 = PaceCrypto.computeAesCmac64(key256, Uint8List(0), macBytes: 16);
    expect(
      mac0.map((b) => b.toRadixString(16).padLeft(2, '0')).join().toUpperCase(),
      '028962F61B7BF89EFC6B551F4667D983',
    );

    // len = 16
    final msg16 = Uint8List.fromList([
      0x6b, 0xc1, 0xbe, 0xe2, 0x2e, 0x40, 0x9f, 0x96,
      0xe9, 0x3d, 0x7e, 0x11, 0x73, 0x93, 0x17, 0x2a
    ]);
    final mac16 = PaceCrypto.computeAesCmac64(key256, msg16, macBytes: 16);
    expect(
      mac16.map((b) => b.toRadixString(16).padLeft(2, '0')).join().toUpperCase(),
      '28A7023F452E8F82BD4BF28D8C37C35C',
    );

    // len = 40
    final msg40 = Uint8List.fromList([
      0x6b, 0xc1, 0xbe, 0xe2, 0x2e, 0x40, 0x9f, 0x96,
      0xe9, 0x3d, 0x7e, 0x11, 0x73, 0x93, 0x17, 0x2a,
      0xae, 0x2d, 0x8a, 0x57, 0x1e, 0x03, 0xac, 0x9c,
      0x9e, 0xb7, 0x6f, 0xac, 0x45, 0xaf, 0x8e, 0x51,
      0x30, 0xc8, 0x1c, 0x46, 0xa3, 0x5c, 0xe4, 0x11
    ]);
    final mac40 = PaceCrypto.computeAesCmac64(key256, msg40, macBytes: 16);
    expect(
      mac40.map((b) => b.toRadixString(16).padLeft(2, '0')).join().toUpperCase(),
      'AAF3D8F1DE5640C232F5B169B9C911E6',
    );

    // len = 64
    final msg64 = Uint8List.fromList([
      0x6b, 0xc1, 0xbe, 0xe2, 0x2e, 0x40, 0x9f, 0x96,
      0xe9, 0x3d, 0x7e, 0x11, 0x73, 0x93, 0x17, 0x2a,
      0xae, 0x2d, 0x8a, 0x57, 0x1e, 0x03, 0xac, 0x9c,
      0x9e, 0xb7, 0x6f, 0xac, 0x45, 0xaf, 0x8e, 0x51,
      0x30, 0xc8, 0x1c, 0x46, 0xa3, 0x5c, 0xe4, 0x11,
      0xe5, 0xfb, 0xc1, 0x19, 0x1a, 0x0a, 0x52, 0xef,
      0xf6, 0x9f, 0x24, 0x45, 0xdf, 0x4f, 0x9b, 0x17,
      0xad, 0x2b, 0x41, 0x7b, 0xe6, 0x6c, 0x37, 0x10
    ]);
    final mac64 = PaceCrypto.computeAesCmac64(key256, msg64, macBytes: 16);
    expect(
      mac64.map((b) => b.toRadixString(16).padLeft(2, '0')).join().toUpperCase(),
      'E1992190549F6ED5696A2C056C315410',
    );
  });

  test('CardAccess OID Bytes Test', () {
    final rawCardAccess = Uint8List.fromList([
      0x31, 0x14, 0x30, 0x12, 0x06, 0x0A, 0x04, 0x00, 0x7F, 0x00, 0x07, 0x02, 0x02, 0x04, 0x02, 0x04, 0x02, 0x01, 0x02, 0x02, 0x01, 0x0C
    ]);
    final info = PaceCrypto.parseCardAccess(rawCardAccess);
    expect(info, isNotNull);
    expect(
      info!.oidBytes.map((b) => b.toRadixString(16).padLeft(2, '0')).join().toUpperCase(),
      '04007F00070202040204',
    );
  });

  test('PACE K_pi Derivation Test Vector from ICAO 9303 / dmrtd', () {
    final kmrz = "T22000129364081251010318";
    final sha1Digest = crypto.sha1.convert(kmrz.codeUnits).bytes;
    final keySeed = Uint8List.fromList(sha1Digest);

    expect(
      keySeed.map((b) => b.toRadixString(16).padLeft(2, '0')).join(),
      '7e2d2a41c74ea0b38cd36f863939bfa8e9032aad',
    );

    final kPi128 = PaceCrypto.derivePaceKey(keySeed, 3, keyBytes: 16);
    expect(
      kPi128.map((b) => b.toRadixString(16).padLeft(2, '0')).join(),
      '89ded1b26624ec1e634c1989302849dd',
    );
  });
}



